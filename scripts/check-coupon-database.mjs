const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role;
create table profiles(id bigint primary key,full_name text,phone text,email text);
create table coupons(id bigint primary key,code text unique,is_active boolean default true,one_use_per_customer boolean default false);
create table orders(id bigint generated by default as identity primary key,phone text,status text,coupon_code text,customer_profile_id bigint,idempotency_key text unique);
create table coupon_usages(id bigint generated by default as identity primary key,coupon_id bigint,profile_id bigint,idempotency_key text,used_at timestamptz default now());
create function create_order_with_coupon_atomic(p_order jsonb,p_items jsonb,p_idempotency_key text,p_coupon_code text,p_discount_amount numeric,p_products_subtotal numeric,p_customer_profile_id bigint)
returns table(id bigint) language plpgsql as $$ declare oid bigint; begin
select orders.id into oid from orders where idempotency_key=p_idempotency_key;
if found then return query select oid; return; end if;
-- Simulate reserving usage BEFORE inserting the order, to verify the guard
-- does not reject the reservation created by the same atomic operation.
if p_coupon_code is not null then insert into coupon_usages(coupon_id,profile_id,idempotency_key) select coupons.id,p_customer_profile_id,p_idempotency_key from coupons where code=p_coupon_code; end if;
insert into orders(phone,status,coupon_code,customer_profile_id,idempotency_key) values(p_order->>'phone',p_order->>'status',p_coupon_code,p_customer_profile_id,p_idempotency_key) returning orders.id into oid;
return query select oid; end $$;
insert into profiles values (1,'One','+963111','one@test'),(2,'Two','+963222','two@test'),(3,'Three','+963333','three@test');
insert into coupons values (1,'WELCOME10',true,true),(2,'PRIVATE',true,true),(3,'PUBLIC',true,false);`);
await db.exec(fs.readFileSync('supabase/migrations/202610110001_coupon_eligibility.sql','utf8'));
